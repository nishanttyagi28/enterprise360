"""Render docs/kpi-catalog.md from kpis.yaml + not_supported.yaml (the only way to edit the catalog).

Usage: python governance/kpi_dictionary/generate_catalog.py [--check]
--check exits 1 if docs/kpi-catalog.md is out of date (used by pytest/CI).
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "docs" / "kpi-catalog.md"
DOMAINS = {"olist": "Olist Brazilian E-Commerce (BRL)", "uci": "UCI Online Retail II (GBP)"}


def render() -> str:
    d = yaml.safe_load((HERE / "kpis.yaml").read_text(encoding="utf-8"))
    ns = yaml.safe_load((HERE / "not_supported.yaml").read_text(encoding="utf-8"))["not_supported"]
    kpis = d["kpis"]
    o = ["# KPI Catalog",
         "",
         "<!-- GENERATED by governance/kpi_dictionary/generate_catalog.py from kpis.yaml — do not hand-edit -->",
         "",
         "Domains are strictly separate: no KPI blends Olist and UCI data, and BRL and GBP are never summed.",
         "Olist GMV = SUM(item_price), freight excluded. UCI Gross Sales = invoiced value. **Neither is recognized revenue.** "
         "Targets/benchmarks: to be set by owner.", ""]
    for dom, title in DOMAINS.items():
        ks = [k for k in kpis if k.get("domain", "olist") == dom]
        if not ks:
            continue
        o += [f"## Domain: {title}", "",
              "| ID | Name | Status | v | Formula | Grain | dbt source | PBI measure | Owner |",
              "|---|---|---|---|---|---|---|---|---|"]
        for k in ks:
            f = k["formula"].replace("|", "\\|")
            o.append(f"| {k['id']} | {k['name']} | {k['status']} | {k['version']} | `{f}` | {k['grain']} | "
                     f"{k['implementations']['dbt']} | {k['implementations']['power_bi_dax']} | {k['owner']} |")
        sm = [(k["id"], m) for k in ks for m in k.get("supporting_measures", [])]
        if sm:
            o += ["", f"### Supporting measures ({dom})", "", "Approved helper measures; not KPIs themselves.", "",
                  "| KPI | Measure | Kind | Purpose |", "|---|---|---|---|"]
            o += [f"| {i} | {m['measure']} | {m['kind']} | {m['purpose']} |" for i, m in sm]
        if dom == "olist":
            for n in d.get("filter_behaviour_notes", []):
                o += ["", f"### {n['title']}", "", f"Applies to: {', '.join(n['applies_to'])}.", "", n["note"]]
        o += ["", f"### Definitions and validation rules ({dom})", ""]
        for k in ks:
            o.append(f"- **{k['id']}** — {k['definition']} Rules: " + "; ".join(k["validation_rules"]))
        nsd = [x for x in ns if x.get("domain", "olist") == dom]
        o += ["", f"### Not supported ({dom})", "", "| KPIs | Reason | Handling |", "|---|---|---|"]
        o += [f"| {x['kpis']} | {x['reason']} | {x['handling']} |" for x in nsd]
        o.append("")
    return "\n".join(o)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/kpi-catalog.md is out of date; run generate_catalog.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
